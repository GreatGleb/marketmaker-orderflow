"""Контракт торговой стратегии.

Граница проведена там же, где она проходит по смыслу: стратегия решает,
когда входить и когда выходить, а всё остальное — выбор донора и пары,
рыночные данные, комиссии, проверка лота, запись результата — общее для
всех и остаётся в симуляторе.

Из этого следует, что стратегия не ходит в базу и не пишет в очередь
результатов. Ей дают готовый контекст и просят решение.

Чтобы добавить новую стратегию, нужно реализовать `Algorithm` и
зарегистрировать ключ в `registry.py`. Цикл симулятора при этом не
трогается — в этом и была цель разделения.
"""
from dataclasses import dataclass, field
from decimal import Decimal
from typing import Any, Optional, Protocol, runtime_checkable


@dataclass
class MarketContext:
    """Всё общее, что стратегия получает готовым.

    `before_entry` оборачивает ожидание до открытия позиции: у копибота
    внутри сидит проверка, не отозван ли выбранный донор. Стратегия про
    доноров ничего не знает — она просто обязана пропускать через эту
    обёртку любое ожидание до входа.
    """

    bot_id: int
    bot_config: Any
    symbol: str
    tick_size: Decimal
    market_data: dict
    commission_rate: Any
    price_provider: Any
    price_watcher: Any
    binance_bot: Any
    before_entry: Any
    # Свечи и ATR. None у путей, где свечи не нужны (боевой бот, тесты
    # legacy): стратегия обязана проверить, прежде чем спрашивать.
    candle_provider: Any = None
    # Ставка maker. Нужна стратегиям с лимитным входом; None — ставка не
    # засеяна, тогда стратегия считает вход по общей.
    maker_commission_rate: Any = None
    # Рабочее место алгоритма на один круг сделки: сюда кладут то, что
    # посчитано при входе и нужно при открытии позиции (например ATR, по
    # которому считался отступ). Симулятор чистит его перед каждым
    # кругом — иначе следующая сделка считалась бы по прошлым числам.
    strategy_state: dict = field(default_factory=dict)
    # Разобранные настройки стратегии: то, что вернул `parse_config`.
    # У legacy здесь пусто — его параметры лежат колонками бота.
    strategy_config: Any = None


@dataclass
class EntryLevels:
    """Уровни входа и сколько ждать их достижения."""

    buy: Decimal
    sell: Decimal
    timeout_seconds: int


@dataclass
class EntryResult:
    """Чем закончилось ожидание входа."""

    trade_type: Optional[str] = None
    price: Optional[Decimal] = None
    timed_out: bool = False

    @property
    def entered(self) -> bool:
        return bool(self.trade_type and self.price and not self.timed_out)


@dataclass
class Position:
    """Открытая позиция глазами стратегии.

    `order` — строка `TestOrder`, которую симулятор потом превращает в
    результат сделки. `state` — рабочее состояние алгоритма на время
    удержания: у `legacy` там уровни выхода и пик цены, у следующей
    стратегии будет своё.
    """

    order: Any
    state: dict = field(default_factory=dict)


@dataclass
class ExitDecision:
    """Решение алгоритма на очередном тике удержания.

    `slippage` — насколько цена закрытия хуже наблюдаемой, в единицах
    цены. Выход рыночный, и на паре с тонким стаканом он исполняется не
    по той цене, по которой сработал триггер. Знак не указывается:
    симулятор применяет проскальзывание против позиции, потому что
    только он знает её направление.
    """

    should_exit: bool = False
    reason: Optional[str] = None
    slippage: Any = None


def signal_price_unchanged(entry: EntryResult, current_price) -> bool:
    """Годится ли сигнал рыночного входа после паузы на проверку донора.

    У копибота между срабатыванием уровня и открытием позиции стоит
    проверка выбора донора — обращение в Redis и в базу. Пока она идёт,
    цена живёт дальше. У стратегии с рыночным входом цена сигнала — это
    цена в момент срабатывания, и перенести старый сигнал на новую цену
    значит записать сделку по цене, по которой ничего не происходило.

    Поэтому условие строгое: цена должна быть ровно та же. Сигнал, не
    доживший до входа, не переносится — следующий проход подождёт новый.

    Стратегиям с лимитным входом это правило **не подходит**, у них своё:
    см. `Algorithm.entry_still_valid`.
    """
    if current_price is None:
        return False

    return Decimal(str(current_price)) == Decimal(str(entry.price))


class ConfigError(ValueError):
    """Настройки стратегии не проходят проверку.

    Бот с такими настройками не запускается: догадываться, что имел в
    виду автор конфига, нельзя — сделки уйдут в общую статистику, и
    отличить их будет нечем.
    """


@runtime_checkable
class Algorithm(Protocol):
    """Что обязана уметь стратегия.

    Версия объявляется здесь же и попадает в каждую сделку
    (`test_orders.algorithm_version`): по ней потом отделяют результаты
    до правки логики от результатов после.
    """

    key: str
    version: str
    # Версия схемы настроек. Не путать с `version`: та отвечает на
    # вопрос «по каким правилам получена сделка», эта — «как читать
    # параметры».
    config_schema_version: int

    def parse_config(self, raw: Optional[dict]) -> Any:
        """Проверяет настройки бота и возвращает их разобранными.

        Неизвестный ключ — ошибка, а не «оставим как есть»: опечатка в
        имени параметра иначе тихо выключила бы его.
        """

    async def prepare(self, context: MarketContext) -> Any:
        """Конфиг бота, приведённый к виду, в котором с ним работают.

        Возвращает конфиг, а не меняет переданный: один и тот же объект
        может использоваться дальше по циклу.
        """

    async def entry_levels(
        self, context: MarketContext, initial_price: Decimal
    ) -> EntryLevels:
        """Уровни входа от текущей цены."""

    async def wait_for_entry(
        self, context: MarketContext, levels: EntryLevels
    ) -> EntryResult:
        """Ждёт достижения уровня. Таймаут — не ошибка, а обычный исход."""

    def open_position(
        self,
        context: MarketContext,
        trade_type: str,
        entry_price: Decimal,
    ) -> Position:
        """Строит позицию и всё, что нужно для решения о выходе."""

    async def entry_still_valid(
        self,
        context: MarketContext,
        entry: EntryResult,
        current_price,
    ) -> bool:
        """Годится ли сигнал после паузы на проверку донора у копибота.

        Спрашивается только у копиботов и только между сигналом и
        открытием позиции: у обычного бота этой паузы нет.

        Отвечать обязана стратегия, потому что ответ следует из того,
        чем является цена входа. У рыночного входа это цена в момент
        срабатывания, и разойтись с текущей она может только потому,
        что сигнал устарел, — годится `signal_price_unchanged`. У
        лимитного входа цена входа это цена заявки: рынок её пробивает,
        то есть расхождение с текущей ценой там не исключение, а
        правило, и та же проверка запретила бы копиботу такие сделки
        вовсе.
        """

    async def should_exit(
        self,
        context: MarketContext,
        position: Position,
        updated_price: Decimal,
        held_seconds: float,
    ) -> ExitDecision:
        """Решение на очередном тике удержания."""
