"""Какие рынки подсистема вообще умеет торговать.

Отбор пар (`app/scripts/seed_watched_pairs.py`) ранжирует по поведению цены и
про инструмент ничего не знает: скачки у токенизированной акции считаются
ровно так же, как у BTC. Поэтому круг кандидатов ограничивается здесь, до
всякого ранжирования.

Ограничение не косметическое. `watched_pair` определяет, по чему питатель
цен собирает историю, а значит и по чему торгуют боты: пара, попавшая сюда
по ошибке, не отсеется дальше — по ней просто пойдут сделки.
"""

# Котируемые валюты, в которых считается баланс и комиссии. Всё остальное на
# фьючерсах Binance — либо мелочь (BTCUSD1, BTCU), либо котировка в монете
# (ETHBTC), где «прибыль в 10 тиков» измеряется в биткоине, а не в долларах,
# и с балансом бота в 1000 условных единиц не сходится.
TRADABLE_QUOTE_ASSETS = ("USDT", "USDC")

# Только бессрочные. Отсюда выпадают две категории, и обе — ловушки:
#
# * CURRENT_QUARTER / NEXT_QUARTER (BTCUSDT_260925) — у поставочных контрактов
#   свой базис к спот-цене и дата экспирации, после которой символ исчезает;
# * TRADIFI_PERPETUAL (AAPLUSDT, NVDAUSDT и ещё 170 штук) — токенизированные
#   акции. Котируются в USDT и по имени неотличимы от крипты, но торгуются в
#   часы американской биржи. Для скальпера на секундном окне это худший из
#   вариантов: большую часть суток тиков нет вовсе, а на открытии рынка гэп
#   выглядит как идеальный «скачок» — то есть отбор их не отсеет, а наоборот
#   поднимет наверх.
