"""Окна, по которым копибот v1 проверяет кандидатов в доноры.

Основное окно у каждого копибота своё — `copy_bot_min_time_profitability_min`,
это и есть перебираемый параметр. А вот два дополнительных фильтра смотрят на
фиксированные окна, и это не упущение: они проверяют не «кто сейчас лучший»,
а «не обманывает ли нас короткое окно». Свойство, которое они ловят,
устойчиво во времени, поэтому мерить его тем же коротким окном бессмысленно —
получилась бы монетка вместо проверки.

Одно значение на оба: сутки — привычная единица для «устойчиво», и держать
здесь два разных числа без причины значило бы объяснять разницу каждому
читающему.
"""

from decimal import Decimal


# Фильтр `copybot_v1_check_for_24h_profitability`: бот обязан быть прибыльным
# не только за своё окно, но и за сутки. Отсекает того, кто выстрелил на
# последних десяти минутах, а до этого сутки терял.
PROFITABILITY_CHECK_MINUTES = 24 * 60

# Фильтр `copybot_v1_exclude_losing_donors`: за какой срок смотреть, чем
# кончилось копирование этого бота у других копиботов.
#
# Раньше здесь стояло окно самого копибота, и на коротких окнах (а их в сетке
# большинство) фильтр вырождался: за десять минут донорской истории почти ни
# у кого нет, а у кого есть — это текущий инкумбент. Сутки дают выборке
# накопиться, и «конфиг у копиров не работает» становится видно.
DONOR_HISTORY_MINUTES = 24 * 60


# --- копибот v3 --------------------------------------------------------------
#
# Третий уровень копирования: v3 выбирает лучшего копибота v2, тот — лучшего v1,
# а тот уже обычного бота. Той же цепочкой ходит боевой `binance_bot`
# (`_get_best_copy_bot`), поэтому сделки ботов v3 — прогноз реальной торговли.

# 12 часов: столько же зашито в боевом боте. Пока значение дублируется в двух
# местах — здесь и в `_get_best_copy_bot`; привести прод к чтению из `test_bots`
# ещё предстоит.
COPYBOT_V3_WINDOW_MINUTES = 720

# Ботов заводят парой, и различает их только флаг компаундинга.
#
# Без флага баланс всегда 1000, как у всего парка: такой бот сравним с
# остальными в общих отчётах. С флагом он ведёт счёт — прибыль
# реинвестируется, в позицию идёт 99% баланса, количество округляется по шагу
# лота. Разница не сводится к множителю: PnL линеен по балансу, а минимальный
# лот нет, и именно он показывает, где реальный бот перестанет торговать.
def copybot_v3_rows() -> list[dict]:
    """Строки `test_bots` для обоих ботов v3.

    Одна фабрика на оба места, которые их заводят: полное пересоздание парка
    (`app/scripts/new_bots.py`) и точечный досев
    (`app/scripts/seed_copybot_v3.py`). Разойдись эти определения — и прогноз
    считался бы ботом, отличающимся от задуманного, а заметить это было бы
    нечем.
    """
    return [
        {
            "symbol": '',
            "balance": Decimal("1000.0"),
            "copybot_v3_time_in_minutes": COPYBOT_V3_WINDOW_MINUTES,
            "copybot_v3_compound_balance": compound,
        }
        for compound in (False, True)
    ]
