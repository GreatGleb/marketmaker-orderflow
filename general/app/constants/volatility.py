from decimal import Decimal

# Ключ, под которым воркер set_volatile_pairs держит самую волатильную пару
# за окно в timeframe минут. Пишет app/workers/volatile_pair.py, читает
# app/bots/demo_test_bot.py — формат обязан совпадать с точностью до символа.
#
# Отсюда и функция: min_timeframe_asset_volatility приходит из БД как
# Decimal('2.00'), из JSON копибота — как строка '2', а в сетке создания
# ботов это float 0.5. Без нормализации получались разные ключи для одного и
# того же таймфрейма (в истории это уже ломалось, коммит f59c071).
VOLATILE_SYMBOL_KEY_PREFIX = "most_volatile_symbol_"

# Сколько ключ живёт в Redis. Если воркер умер, ключ протухает и боты
# останавливаются, а не торгуют устаревшей парой (коммит a8ac380).
VOLATILE_SYMBOL_TTL_SECONDS = 60


def most_volatile_symbol_key(timeframe) -> str:
    # format(..., 'f') — чтобы 10 минут не превратились в '1E+1'.
    normalized = format(Decimal(str(timeframe)).normalize(), 'f')

    return f"{VOLATILE_SYMBOL_KEY_PREFIX}{normalized}"


# Отсечки для отбора самой волатильной пары (app/crud/asset_history.py).
#
# Сам размах (max-min)/min без них выигрывает мусор: у неликвида один
# случайный или битый тик даёт «волатильность» в разы больше, чем настоящее
# движение у ликвидной пары. Бот при этом ничем не защищён — пару он берёт
# как есть и идёт торговать монетой, которой нет в стакане.

# Оборот за сутки в USDT. Такой же порог стоит на отборе watched-пар
# (app/scripts/seed_watched_pairs.py): ниже него движение цены — это чаще
# всего одна случайная сделка, а не то, во что можно войти и выйти.
MIN_QUOTE_VOLUME_24H = 2_000_000

# Планка по числу тиков — доля от медианы по парам самого окна. Абсолютная
# частота тут не годится: сколько тиков придёт, решает режим питателя цен, и
# на истории за август (futures ws, 6-12 тиков в минуту) планка в 20 тиков на
# минуту отсекала вообще всех — боты встали бы, вместо того чтобы взять
# лучшее из доступного. Относительная планка калибруется сама: она убирает
# пары, отстающие от остальных в этом же окне, и не может отсечь всех.
MIN_TICKS_SHARE_OF_MEDIAN = 0.25

# И абсолютный минимум: по нескольким тикам нельзя ни посчитать размах, ни
# отличить выброс от движения, даже если все пары в окне такие же редкие.
MIN_TICKS_IN_WINDOW = 10

# Сколько крайних тиков с каждой стороны выбрасывается перед расчётом
# размаха. Выброс отличается от настоящего движения не размером, а
# одиночностью: по одной сделке ордер не поставить, а на настоящем ходе тиков
# у края много. Поэтому отсекается не «всё дальше N процентов» — так резалось
# бы и реальное сильное движение, — а ровно пара самых крайних отпечатков.
# На истории за август победитель от этого ни в одном окне не поменялся, а
# его размах опустился на 0.02-0.33 п.п. — настоящие движения отбрасывание
# крайних тиков практически не задевает.
MAX_DROPPED_TICKS = 2

# Выбросить два тика можно только там, где тиков много. Разрешаем один
# отброшенный на каждые TICKS_PER_DROPPED_TICK тиков окна: на 10 тиках не
# выбрасывается ничего (там от мусора спасает сам минимум по тикам), на 40 и
# больше — оба.
TICKS_PER_DROPPED_TICK = 20

# Сколько пар отбирается по сырому размаху, прежде чем у них пересчитают
# размах без крайних тиков. Достать крайние цены по десяти парам дёшево, а
# сортировать всё окно — нет: на часовом окне это 0.6 с против 9 с.
# Настоящий победитель в первую десятку по сырому размаху попадает всегда:
# чтобы он в неё не попал, надутыми выбросами должны оказаться сразу десять
# пар.
VOLATILITY_CANDIDATES = 10
