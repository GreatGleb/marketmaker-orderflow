"""Пары, на которых прямо сейчас держат позиции.

Состояние открытых позиций живёт в памяти процессов симулятора: в базу
пишется уже закрытая сделка. Поэтому пересборка списка отслеживаемых пар
до сих пор не могла узнать, что пара кому-то нужна, и могла её удалить —
а вместе с ней исчезали котировки, по которым позицию нужно закрывать.

Каждый шард публикует свой список занятых пар в Redis с коротким TTL.
Короткий — чтобы упавший процесс не держал подписку вечно: не обновил
ключ, и через минуту его пары перестают считаться занятыми. Отсюда и
период обновления: он должен быть заметно меньше TTL.
"""

OPEN_POSITION_SYMBOLS_PREFIX = "open_position_symbols"

# Ключ переживает две пропущенные публикации подряд — сеть и нагрузка
# не должны выдавать живой процесс за мёртвый.
OPEN_POSITION_SYMBOLS_TTL_SECONDS = 60

OPEN_POSITION_PUBLISH_INTERVAL_SECONDS = 20


def open_position_symbols_key(shard: int) -> str:
    return f"{OPEN_POSITION_SYMBOLS_PREFIX}:{shard}"
