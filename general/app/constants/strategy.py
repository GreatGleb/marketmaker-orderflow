"""Ключи стратегий и версия алгоритма.

Ключ стратегии — строка, а не числовой `id`: числа выдаёт база, и в
разных развёртываниях они разные, поэтому код, сиды и конфиги ссылаются
на ключ, а `strategies.id` живёт только внутри строк таблиц.
"""

# Текущий (и пока единственный) алгоритм: вход по движению на
# `start_updown_*`, выход по стоп-уровням, правилу 30 секунд и MA.
# Название техническое: «legacy» не означает, что алгоритм устарел, —
# только что он был здесь до разделения на стратегии.
STRATEGY_LEGACY = "legacy"

# Стратегия прострелов. Правила задаются настройками бота, а не зашиты:
# именно их и предстоит перебирать.
STRATEGY_0 = "strategy_0"

# Возврат к средней: лимитка на отступе в ATR ловит вынос, выход — на
# возврате. Отличается от strategy_0 моментом входа, а не событием.
STRATEGY_1 = "strategy_1"

# Человеческие названия: их видит тот, кто смотрит в таблицу
# `strategies`. Ключ технический и в отчётах не расшифровывается.
STRATEGY_TITLES = {
    STRATEGY_LEGACY: "Текущий алгоритм",
    STRATEGY_0: "Прострелы",
    STRATEGY_1: "Возврат к средней",
}


# Версия алгоритма фиксируется в сделке при открытии позиции и отвечает
# на вопрос «по каким правилам эта сделка получилась». Менять при каждой
# правке логики входа/выхода: иначе сделки до и после правки сольются в
# одну статистику и сравнивать их будет нечем.
#
# Версия схемы конфига — отдельное понятие, здесь её нет.
LEGACY_ALGORITHM_VERSION = "legacy-1"

# У сделок, записанных до появления этих полей, версия неизвестна. Не
# «legacy-1»: приписать старой истории сегодняшнюю логику — значит
# потерять границу между «до исправлений» и «после».
UNKNOWN_ALGORITHM_VERSION = None

# Версия по ключу стратегии. Пока стратегия одна, но версия берётся
# отсюда, а не подставляется константой по месту: в день, когда появится
# вторая, забытая подстановка запишет её сделкам чужую версию.
ALGORITHM_VERSIONS = {
    STRATEGY_LEGACY: LEGACY_ALGORITHM_VERSION,
    STRATEGY_0: "strategy_0-1",
    STRATEGY_1: "strategy_1-1",
}


def algorithm_version_for(strategy_key) -> str | None:
    """Версия алгоритма стратегии; `None` у незарегистрированной.

    `None` здесь значит «версия неизвестна» — ровно то же, что у старых
    сделок. Выдумывать версию для стратегии, о которой код ничего не
    знает, нельзя: по ней потом будут сравнивать результаты.
    """
    return ALGORITHM_VERSIONS.get(strategy_key)


