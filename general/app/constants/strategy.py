# Пул доноров копибота (`test_bots.donor_scope`).
#
# {"mode": "all"} — любые стратегии, включая подключённые позже.
# {"mode": "list", "strategies": ["legacy"]} — только перечисленные;
# пустой список означает, что кандидатов нет вовсе.
DONOR_SCOPE_MODE_ALL = "all"
DONOR_SCOPE_MODE_LIST = "list"

DONOR_SCOPE_ALL = {"mode": DONOR_SCOPE_MODE_ALL}


def donor_scope_list(*strategy_keys: str) -> dict:
    """Пул из перечисленных стратегий."""
    return {"mode": DONOR_SCOPE_MODE_LIST, "strategies": list(strategy_keys)}


def scope_allows(scope, strategy_key) -> bool:
    """Разрешает ли пул исполнение этой стратегии.

    Проверка по факту, а не по составу цепочки: копибот может прийти к
    донору чужой стратегии через промежуточные звенья своего парка, и
    смотреть надо на того, чьим алгоритмом в итоге торгуют.
    """
    keys = donor_scope_keys(scope)

    if keys is None:
        return True

    return strategy_key in keys


def donor_scope_keys(scope) -> list[str] | None:
    """Ключи стратегий пула; `None` — ограничений нет.

    Пустой список и `None` — разные ответы: первый означает «кандидатов
    нет», второй — «годится любая стратегия». Их легко перепутать в
    проверке `if not keys`, поэтому здесь они разведены явно.
    """
    if not scope:
        # Поле пустое у некопиботов и у копиботов, заведённых до
        # появления пула. Ограничений нет — прежнее поведение.
        return None

    if scope.get("mode") == DONOR_SCOPE_MODE_ALL:
        return None

    return list(scope.get("strategies") or [])
