from decimal import Decimal

from pydantic import Field, field_validator, model_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    DB_URL: str = (
        "postgresql+asyncpg://postgres:secret@localhost:5432/postgres"
    )

    # Адрес Redis: цены, очередь сделок, ключи копиботов, флаги симулятора.
    # Умолчание — имя сервиса из docker-compose, то есть работает только
    # внутри его сети. Запуск снаружи (отладка с хоста, Redis на отдельной
    # машине) задаётся здесь, а не правкой кода:
    #   REDIS_URL=redis://localhost:6380/0
    REDIS_URL: str = "redis://redis:6379/0"

    # Брокер celery (он же backend результатов). Пусто — тот же Redis, что
    # и у всего остального. Отдельная переменная оставлена потому, что
    # брокер иногда уносят на свой инстанс, чтобы очередь задач не делила
    # память с ценами.
    #
    # Celery предпочёл бы этой настройке переменные окружения
    # `CELERY_BROKER_URL` и `CELERY_RESULT_BACKEND`, поэтому `app/tasks.py`
    # перезаписывает их отсюда. Единственный источник адреса — эта строка.
    CELERY_BROKER: str = ""

    # Максимальный номинал покупки при отборе пар, без плеча и комиссий.
    WATCHED_PAIR_MAX_BUY_NOTIONAL_USDT: Decimal = Field(
        default=Decimal("9"), gt=0, allow_inf_nan=False
    )

    # Источник рыночных данных:
    #   ws         - фьючерсный !ticker@arr, исходное поведение. Снимок
    #                раз в секунду, bid/ask в нём нет вовсе
    #   futures_ws - фьючерсный @bookTicker: края книги и тиковая частота
    #   rest       - поллинг /fapi/v1/ticker/24hr (когда push недоступен)
    #   spot_ws    - спотовый поток, если фьючерсный молчит
    MARKET_DATA_SOURCE: str = "ws"
    MARKET_DATA_REST_INTERVAL_SEC: float = 2.0

    # futures_ws: как часто обновлять цену в Redis, сек. Чаще, чем
    # обновляется кэш симулятора (PriceCache.REFRESH_INTERVAL_SECONDS =
    # 0.05), смысла нет — в ключе всё равно живёт одно значение.
    MARKET_DATA_PUBLISH_SEC: float = 0.05
    # futures_ws: как часто писать строку в asset_history, сек. Одна
    # строка на пару за интервал. При 834 тиках в секунду на 55 парах
    # запись каждого тика дала бы 72 млн строк в сутки; секунда держит ту
    # же плотность, что давал !ticker@arr, и не трогает ни диск, ни
    # статистику волатильности.
    MARKET_DATA_HISTORY_SEC: float = 1.0

    # spot_ws: по каким парам подписываться.
    #   watched - только пары из watched_pair (по умолчанию)
    #   all     - все спотовые USDT-пары, у которых есть запись
    #             в asset_exchange_specs (остальные писать некуда)
    MARKET_DATA_SPOT_SYMBOLS: str = "watched"
    # spot_ws: какой стрим гонит частоту.
    #   bookTicker - любое изменение лучших bid/ask (~40 мс на ликвидной паре),
    #                last_price пишется как середина спреда (bid+ask)/2
    #   aggTrade   - только реальные сделки (реже), last_price = цена сделки
    MARKET_DATA_SPOT_STREAM: str = "bookTicker"
    # spot_ws: как часто сбрасывать накопленные тики в БД, сек.
    # Тики ловятся все, батч только уменьшает число коммитов.
    MARKET_DATA_SPOT_FLUSH_SEC: float = 0.2
    # Чем помечать источник в asset_history для спотовых котировок.
    MARKET_DATA_SPOT_SOURCE: str = "BINANCE_SPOT"

    # Источник минутных свечей (`candles:{SYMBOL}` в Redis):
    #   ws        - поток @kline_1m фьючерсов, исходное поведение
    #   rest      - поллинг фьючерсного /fapi/v1/klines
    #   spot_rest - поллинг спотового /api/v3/klines
    # REST нужен по той же причине, что и MARKET_DATA_SOURCE=rest:
    # фьючерсный WS с текущего IP принимает подписку и молчит, а REST
    # fapi этим не задет. Рынок свечей обязан совпадать с рынком цен,
    # иначе бот считает волатильность по одному, а торгует по другому.
    CANDLES_SOURCE: str = "ws"
    # spot_rest: как часто опрашивать. Свеча минутная, поэтому чаще, чем
    # раз в полминуты, смысла нет — только вес запросов.
    CANDLES_REST_INTERVAL_SEC: float = 30.0
    # spot_rest: сколько пар опрашивать одновременно. Вес /klines = 2 при
    # limit <= 100, лимит IP — 6000 в минуту.
    CANDLES_REST_CONCURRENCY: int = 8
    # Как часто перечитывать список пар из test_bots, сек.
    CANDLES_SYMBOLS_REFRESH_SEC: float = 600.0

    # --- Стакан (order_book_listener) --------------------------------------
    # Поток `@depth20@100ms`: двадцать уровней с каждой стороны, готовый
    # снимок. Предыдущая версия слушателя сидела на `@depth` — это дельты
    # книги, по ним OBI не считается вовсе.
    #
    # Построчной записи в Postgres здесь нет намеренно: на 55 парах это
    # ~550 сообщений в секунду с двумя JSON-массивами в каждом. В рантайм
    # идёт Redis, в архив — суточные файлы на диск.

    # По каким парам слушать стакан:
    #   watched - только watched_pair, то есть парк (по умолчанию)
    #   all     - все торгуемые бессрочные контракты USDⓈ-M
    #
    # `all` нужен офлайн-счёту, а не парку. Прострелов 2% за секунду на
    # 55 парах около 47 в сутки, и статистика по OBI набирается месяц;
    # на 570 парах — те же полторы тысячи событий за трое суток.
    # Состав `watched_pair` при этом не меняется: список торгуемых
    # контрактов читается из fapi и никуда не пишется.
    ORDER_BOOK_SYMBOLS: str = "watched"
    # Частота потока: 100ms, 250ms или 500ms.
    #
    # В архив всё равно идёт снимок раз в секунду
    # (ORDER_BOOK_ARCHIVE_SEC), поэтому для сбора статистики по сотням
    # пар 100 мс — это впятеро больше трафика без единой лишней строки.
    # 100ms оставлено умолчанием для парка: рантайму нужна частота,
    # стратегии опрашивают признаки раз в 100 мс.
    ORDER_BOOK_STREAM_SPEED: str = "100ms"

    # Каталог архива. Внутри контейнера это точка монтирования из
    # docker-compose; снаружи — BINANCE_HISTORY_DIR хоста.
    ORDER_BOOK_ARCHIVE_DIR: str = "/data/binance-history/order_book"
    # Как часто класть снимок в архив, сек. Один на пару за интервал.
    # Полная частота потока (10 снимков в секунду на пару) даёт порядка
    # 40 ГБ в сутки до сжатия — для счёта порогов по OBI это избыточно,
    # секунды хватает. Ноль означает «писать каждый пришедший снимок».
    ORDER_BOOK_ARCHIVE_SEC: float = 1.0
    # Как часто обновлять снимок в Redis, сек. Стратегии опрашивают
    # признаки раз в 100 мс, чаще публиковать нечего.
    ORDER_BOOK_PUBLISH_SEC: float = 0.1
    # Сколько живёт ключ в Redis. Короткий срок — чтобы потребитель
    # получал отсутствие данных, а не вчерашнюю книгу.
    ORDER_BOOK_REDIS_TTL_SEC: float = 5.0
    # Сколько уровней класть в архив и в Redis. Двадцать — всё, что даёт
    # поток; меньше ставят, когда важнее место на диске.
    ORDER_BOOK_LEVELS: int = 20
    # По сколько стримов держать на одном сокете. Замер 2026-09-24: на
    # плохом канале одно соединение упирается в потолок около 20
    # сообщений в секунду **независимо от числа стримов** и вдобавок
    # рвётся каждые 25-50 секунд. Те же пять стримов, разложенные по
    # пяти сокетам, дали 44 сообщения в секунду и ноль обрывов. Ноль
    # означает «все стримы одним сокетом», как было раньше.
    ORDER_BOOK_STREAMS_PER_SOCKET: int = 5
    # Сколько секунд молчания считать отказом. Именно так ловится пункт
    # 29 в 08-gotchas.md: неверный базовый URL подписку подтверждает и
    # данных не шлёт, поэтому проверяем факт пришедших фреймов, а не то,
    # что соединение установилось.
    ORDER_BOOK_SILENCE_LIMIT_SEC: float = 30.0

    # --- Ретеншн -----------------------------------------------------------
    # База растёт на гигабайты в сутки: asset_history пишет каждый тик,
    # test_orders — каждую закрытую сделку всех ботов. Без чистки диск
    # кончается за неделю, поэтому по умолчанию она включена.
    RETENTION_ENABLED: bool = True

    # Сколько держать сырые строки, в часах.
    # asset_history нужен только «прямо сейчас»: цены боты берут из Redis, а
    # запросы волатильности смотрят назад максимум на сутки.
    RETENTION_ASSET_HISTORY_HOURS: float = 24
    # test_orders нужен копиботам: самое длинное окно прибыльности — 2880
    # минут (48 часов), см. new_bots.py. Меньше 48 ставить нельзя, иначе
    # длинные окна начнут считаться по обрезанной истории. 72 — это те же
    # 48 часов плюс сутки запаса на случай, если чистка простояла.
    RETENTION_TEST_ORDERS_HOURS: float = 72
    # asset_order_book — снимки стакана, дальше суток не читаются.
    RETENTION_ORDER_BOOK_HOURS: float = 24

    # Удаление идёт пачками: один DELETE на десятки миллионов строк держит
    # блокировки и раздувает WAL так, что база встаёт колом.
    RETENTION_BATCH_ROWS: int = 50_000
    # Сколько всего секунд одному проходу разрешено занимать базу. Не успел —
    # доберёт на следующем часе, а не будет мешать ботам весь день.
    RETENTION_MAX_SECONDS: float = 900

    # pg_repack после чистки возвращает место операционной системе, но требует
    # свободного места в размер таблицы вместе с её индексами. На заполненном
    # диске это верный способ добить сервер, поэтому по умолчанию выключено:
    # обычного DELETE достаточно, чтобы таблица перестала расти.
    RETENTION_REPACK: bool = False

    # --- Свёртки по test_orders -------------------------------------------
    # Сырые сделки — результат эксперимента, просто стереть их нельзя.
    # Перед удалением каждый десятиминутный блок сворачивается в одну строку
    # на (бот, пара, реферальный бот), и статистика переживает чистку.
    ROLLUP_ENABLED: bool = True
    # Шаг блока. Десять минут выбраны потому, что все окна копиботов кратны
    # десяти (10, 20, ..., 1440, 2880) и собираются из целых блоков без потерь.
    ROLLUP_BUCKET_MINUTES: int = 10
    # Блок закрывается не сразу: сделки идут в базу через очередь в Redis и
    # попадают туда с задержкой. Запас в час гарантирует, что в уже свёрнутый
    # блок ничего не долетит.
    ROLLUP_LAG_MINUTES: float = 60
    # Потолок времени на один проход — чтобы разбор накопившегося хвоста
    # не занял базу на весь день.
    ROLLUP_MAX_SECONDS: float = 300
    # Сколько хранить сами свёртки. `None` — хранить бессрочно.
    #
    # По умолчанию свёртки не удаляются никогда: это единственное, что
    # остаётся от эксперимента после чистки сырых сделок, и решение выбросить
    # их принимает человек, а не расписание.
    #
    # Но расти они будут, и считать надо заранее. Объём не зависит от числа
    # сделок — только от числа ботов: каждый активный бот даёт строку на
    # каждый десятиминутный блок. Замерено на парке в 17 236 ботов: 2.48 млн
    # строк в сутки, 269 байт на строку с индексами, то есть 637 МБ в сутки.
    #
    #    2 месяца →  38 ГБ      6 месяцев → 113 ГБ
    #    4 месяца →  76 ГБ      год       → 227 ГБ
    #
    # На диске в 80 ГБ рядом с 72 часами сырых сделок это примерно два
    # месяца. Дальше — либо свёртки свёрток (шаг час или сутки вместо десяти
    # минут), либо выгрузка в архив, либо срок хранения тут.
    # Для парка поменьше делить пропорционально: 637 МБ × ботов / 17236.
    #
    # Ноль и отрицательные значения тоже означают «не удалять»: пустая или
    # кривая настройка не должна оборачиваться потерей данных.
    RETENTION_ROLLUP_DAYS: int | None = None

    ENVIRONMENT: str = "local"

    TELEGRAM_BOT_TOKEN: str = ""
    TELEGRAM_CHAT_ID: str = ""

    TELEGRAM_TEST_BOT_TOPIC_ID: str = ""
    TELEGRAM_CELERY_TOPIC_ID: str = ""

    @model_validator(mode="after")
    def _celery_broker_defaults_to_redis(self):
        """Не задан брокер — берём общий Redis.

        Два адреса, которые почти всегда совпадают, — это один переезд,
        после которого половина системы смотрит в новый Redis, а celery
        молча продолжает стучаться в старый.
        """
        if not self.CELERY_BROKER.strip():
            self.CELERY_BROKER = self.REDIS_URL

        return self

    @field_validator("RETENTION_ROLLUP_DAYS", mode="before")
    @classmethod
    def _blank_means_forever(cls, value):
        """Пустое значение в .env — это «хранить бессрочно», а не ошибка.

        Без этого `RETENTION_ROLLUP_DAYS=` роняет разбор настроек, а вместе
        с ним и `alembic upgrade head` в boot.sh — то есть контейнер вообще
        не поднимется из-за пустой строки в конфиге.
        """
        if isinstance(value, str) and not value.strip():
            return None

        return value

    model_config = SettingsConfigDict(env_file="../.env")


settings = Settings()
