# Почему 0.05, а не меньше.
#
# У прохода autovacuum есть фиксированная цена — обход всех индексов целиком,
# независимо от того, сколько мёртвых строк он нашёл. Замер на 2 млн строк с
# тремя индексами: 103 мс при 0.5% мусора против 239 мс при 20%. То есть
# убрать 400 тысяч мёртвых строк сорока мелкими проходами стоит 4.1 с, а
# одним крупным — 0.24 с. Чем чаще, тем дороже суммарно.
#
# С другой стороны, всё, что накопилось между проходами, лежит на диске.
#
#   scale   срабатывает   мусора на диске
#   0.2      раз в 14.4 ч        7.8 ГБ   (умолчание Postgres)
#   0.05     раз в 3.6 ч         2.0 ГБ   ← выбрано
#   0.01     раз в 0.7 ч         0.4 ГБ
#
# 0.05 — середина: экономит около 6 ГБ на диске в 80 ГБ ценой четырёх
# проходов вместо одного. Меньше брать незачем: выигрыш по месту дальше
# мелкий, а суммарная работа растёт линейно.
#
# `asset_history` намеренно оставлена с умолчанием: вся таблица меньше
# гигабайта (24 часа хранения), экономить там нечего, а индексов у неё шесть
# и проход самый дорогой из всех.
#
# Блокировок это не добавляет: обычный VACUUM берёт ShareUpdateExclusiveLock,
# который не конфликтует ни с INSERT, ни с SELECT. Чаще — значит чаще, но
# по-прежнему незаметно для ботов.
SCALE_FACTOR = 0.05


